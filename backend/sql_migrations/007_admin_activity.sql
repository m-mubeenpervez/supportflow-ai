-- Run on the verified recovery database only. Never on the original damaged DB.
BEGIN;
CREATE TABLE IF NOT EXISTS public.admin_activity_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id integer NOT NULL,
    actor_email varchar(255) NOT NULL,
    action varchar(60) NOT NULL,
    entity_type varchar(30) NOT NULL,
    entity_id integer NOT NULL,
    description text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_admin_activity_actor_created
    ON public.admin_activity_events (actor_id, created_at DESC);
COMMIT;
